// Builds the core as WebAssembly for the JS wrapper: cargo (opt-level z, LTO, SIMD), then
// wasm-opt when it is installed, then `js/wasm.ts`, the module as base64, so `read` stays
// synchronous with no fetch and no `await init()`. Prints the sizes.
//
//   bun rust/cells-wasm/build.ts

import { brotliCompressSync, constants, gzipSync } from "node:zlib"

const here = import.meta.dir
const root = `${here}/..`
const built = `${root}/target/wasm32-unknown-unknown/wasm/cells_wasm.wasm`
const out = `${here}/js/cells.wasm`

const run = (cmd: string[]) => {
  const p = Bun.spawnSync(cmd, { cwd: root, stdout: "inherit", stderr: "inherit" })
  if (p.exitCode !== 0) throw new Error(`${cmd.join(" ")} exited ${p.exitCode}`)
}

run(["cargo", "build", "-p", "cells-wasm", "--target", "wasm32-unknown-unknown", "--profile", "wasm"])
const raw = await Bun.file(built).bytes()
if (Bun.which("wasm-opt")) {
  run(["wasm-opt", "-Oz", "--enable-simd", "--enable-bulk-memory", "--enable-nontrapping-float-to-int", "--enable-sign-ext", "--enable-mutable-globals", built, "-o", out])
} else {
  console.log("wasm-opt is not installed: the module is cargo's alone")
  await Bun.write(out, raw)
}
const wasm = await Bun.file(out).bytes()
await Bun.write(
  `${here}/js/wasm.ts`,
  `// Generated by build.ts from cells.wasm: the module as base64. Never edited by hand.\nexport const wasm = "${Buffer.from(wasm).toString("base64")}"\n`,
)
const gz = gzipSync(wasm, { level: 9 }).length
const br = brotliCompressSync(wasm, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }).length
const kb = (n: number) => `${(n / 1024).toFixed(1)} KB`
console.log(`cargo ${kb(raw.length)}, wasm-opt ${kb(wasm.length)}, gzip ${kb(gz)}, brotli ${kb(br)}`)
