const source = readFileSync(join(root, "queries/highlights.scm"), "utf8")
const injections = readFileSync(join(root, "queries/injections.scm"), "utf8")

// The canonical file's first paragraph says which names it uses; the rest
// holds for every editor.
const lines = source.split("\n")
const intro = lines.indexOf(";")
if (intro < 0) throw new Error("queries/highlights.scm lost its intro paragraph, ended by a lone ;")
const body = [";", ...lines.slice(intro + 1)].join("\n")

function write(editor: string, names: Names, dir: string, from: string) {
  const renamed = body.replace(/ @([a-z.]+)/g, (_, name: string) => {
    if (!(name in names)) throw new Error(`no ${editor} name for @${name}: add it to ${editor.toUpperCase()}`)
    const to = names[name]
    return to === null ? "" : ` @${to}`
  })
  const header = `; GENERATED by tree-sitter/scripts/queries.ts from ${from}, in ${editor}'s
; names. Edit the canonical file and run the script again.
`
  mkdirSync(dir, { recursive: true })
  writeFileSync(join(dir, "highlights.scm"), header + renamed)
  writeFileSync(join(dir, "injections.scm"), injections)
  console.log(`wrote ${join(dir, "highlights.scm")} and injections.scm`)
}

write("Helix", HELIX, join(root, "queries/helix"), "../highlights.scm")
write("Zed", ZED, join(root, "../editors/zed/languages/cells"), "tree-sitter/queries/highlights.scm")

// Zed fetches the grammar from GitHub at the commit extension.toml names: the
// last one that changed the parser, so the queries above are read by the
// parser they were written for. A parser not yet committed has no commit to name.
const dirty = Bun.spawnSync(["git", "status", "--porcelain", "--", "src", "grammar.js"], { cwd: root }).stdout.toString()
if (dirty.trim() !== "") throw new Error(`the parser has changes not committed, so Zed has no commit to fetch:\n${dirty}`)
const rev = Bun.spawnSync(["git", "log", "-1", "--format=%H", "--", "src", "grammar.js"], { cwd: root }).stdout.toString().trim()
if (!/^[0-9a-f]{40}$/.test(rev)) throw new Error(`no commit changed the parser: ${rev}`)
const manifest = join(root, "../editors/zed/extension.toml")
const toml = readFileSync(manifest, "utf8")
const pinned = toml.replace(/^rev = "[0-9a-f]{40}"$/m, `rev = "${rev}"`)
if (!/^rev = "[0-9a-f]{40}"$/m.test(toml)) throw new Error(`${manifest} lost its grammar's rev line`)
writeFileSync(manifest, pinned)
console.log(`${manifest}: the grammar at ${rev}, which Zed fetches once it is pushed`)
