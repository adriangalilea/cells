// queries/helix/highlights.scm, from queries/highlights.scm with each capture
// renamed to Helix's scope for it. The canonical file is the one written by
// hand; this one is never edited.
//
//   bun run scripts/helix-queries.ts

import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dir, "..")

// Every capture the canonical file uses, and Helix's name for it. A capture
// missing here stops the script, so a new one is never silently left in
// Neovim's spelling.
const HELIX: Record<string, string | null> = {
  "attribute": "attribute",
  "boolean": "constant.builtin.boolean",
  "comment": "comment.line",
  "constant": "type.enum.variant",
  "constant.builtin": "constant.builtin",
  "constant.builtin.computed": "constant.builtin.computed",
  "function": "function",
  "keyword": "keyword",
  "keyword.import": "keyword.control.import",
  "keyword.modifier": "keyword.storage.modifier",
  "keyword.operator": "keyword.operator",
  "keyword.type": "keyword.storage.type",
  "label": "label",
  "module": "namespace",
  "number": "constant.numeric",
  "operator": "operator",
  "punctuation.bracket": "punctuation.bracket",
  "punctuation.delimiter": "punctuation.delimiter",
  "punctuation.special": "punctuation.special",
  "spell": null,
  "string": "string",
  "string.escape": "constant.character.escape",
  "string.special": "string.special",
  "string.special.path": "string.special.path",
  "string.special.url": "string.special.url",
  "tag": "tag",
  "type": "type",
  "type.builtin": "type.builtin",
  "type.definition": "type",
  "variable": "variable",
  "variable.builtin": "variable.builtin",
  "variable.member": "variable.other.member",
  "variable.parameter": "variable.parameter",
}

const source = readFileSync(join(root, "queries/highlights.scm"), "utf8")

const header = `; GENERATED by scripts/helix-queries.ts from ../highlights.scm, in Helix's
; scope names. Edit the canonical file and run the script again.
`

// The canonical file's first paragraph says which names it uses; the rest
// holds for both.
const lines = source.split("\n")
const intro = lines.indexOf(";")
if (intro < 0) throw new Error("queries/highlights.scm lost its intro paragraph, ended by a lone ;")

const body = [";", ...lines.slice(intro + 1)]
  .join("\n")
  .replace(/ @([a-z.]+)/g, (_, name: string) => {
    if (!(name in HELIX)) throw new Error(`no Helix scope for @${name}: add it to HELIX`)
    const helix = HELIX[name]
    return helix === null ? "" : ` @${helix}`
  })

mkdirSync(join(root, "queries/helix"), { recursive: true })
writeFileSync(join(root, "queries/helix/highlights.scm"), header + body)
// Injections name languages, not scopes: the same file serves Helix.
writeFileSync(join(root, "queries/helix/injections.scm"), readFileSync(join(root, "queries/injections.scm"), "utf8"))
console.log("wrote queries/helix/highlights.scm and injections.scm")
